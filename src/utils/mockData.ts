export function generateSamplePriceHistory(
  currentPrice: number,
  currency: 'INR' | 'USD' | 'EUR' | 'GBP',
  storeName: string
) {
  const dates = ['30d ago', '21d ago', '14d ago', '7d ago', '3d ago', 'Today'];
  // Realistic price volatility: was higher, dipped, fluctuated
  const multipliers = [1.25, 1.2, 1.35, 1.15, 1.05, 1.0];
  return dates.map((d, i) => {
    const p = Math.round(currentPrice * multipliers[i]);
    return {
      date: d,
      price: p,
      currency,
      storeName,
      isLowest: i === 5,
    };
  });
}

